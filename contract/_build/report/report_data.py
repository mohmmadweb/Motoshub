def cats(P, S, D):
    out = []
    for (cat, srcx, crit, items, _r, _w), st, desc in zip(P, S, D):
        assert len(items) == len(st), cat
        out.append({"cat": cat, "crit": crit, "desc": desc, "plan": PLAN.get(cat, ""),
                    "items": [{"t": t, "s": s} for t, s in zip(items, st)]})
    return out



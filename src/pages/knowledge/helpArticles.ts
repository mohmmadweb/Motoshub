/** حداکثر سه مقاله‌ی راهنمای مرتبط با مسیر فعلی */
export function helpForPath(path: string, settings: WorkflowSettings, max = 3): Article[] {
  const p = path.split("?")[0];
  const ids = routeHelp.find(([pre]) => (pre === "/dashboard" ? p === pre || p === `${pre}/` : p.startsWith(pre)))?.[1] ?? [];
  const all = buildArticles(settings);
  return ids.map((id) => all.find((a) => a.id === id)).filter((a): a is Article => !!a).slice(0, max);
}

const nrm = (t: string) => t.replace(/ي/g, "ی").replace(/ك/g, "ک").replace(/\u200c/g, " ").toLowerCase();
/** جستجوی مقاله برای یک متن آزاد (مثلاً عنوان تیکت) — امتیاز بر اساس واژه‌های مشترک */
export function searchHelp(text: string, settings: WorkflowSettings, max = 3): Article[] {
  const words = nrm(text)
    .split(/[\s،,.؟?!:؛()«»"']+/)
    .filter((w) => w.length >= 3);
  if (!words.length) return [];
  return buildArticles(settings)
    .map((a) => {
      const title = nrm(a.title);
      const hay = nrm([a.summary, ...(a.tags ?? []), ...(a.steps ?? []), ...(a.body ?? [])].join(" "));
      const score = words.reduce((acc, w) => acc + (title.includes(w) ? 3 : 0) + ((a.tags ?? []).some((t) => nrm(t).includes(w)) ? 2 : 0) + (hay.includes(w) ? 1 : 0), 0);
      return { a, score };
    })
    .filter((x) => x.score >= 2)
    .sort((x, y) => y.score - x.score)
    .slice(0, max)
    .map((x) => x.a);
}
